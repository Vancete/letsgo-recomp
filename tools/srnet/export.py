"""The trained network's weights -> runtime/nvn/vulkan/srnet_weights.h: its three layers as straight-line GLSL for
srnet.comp / srnet16.comp (exec.c srnet_run), the weights as literals rounded to half precision (FP16, the precision
the network was checked in: evaluate.py). Literals, not arrays: indexed in loops the arrays went to memory (an FP16
variant took 20 ms at 1280 x 720, the FP32 one 3 ms before its loops were unrolled).

python export.py srnet_v1.pt [../../runtime/nvn/vulkan/srnet_weights.h [prefix]]

prefix (default srnet): the names' - srnet_s with a student of the teacher (LOCAL research: its header,
srnet_student.h, is never committed). The width of the hidden layers (<PREFIX>_HID) and the detail residual's ratio
(<PREFIX>_RES, 0: none) come from the weights.

The shader declares T (float / float16_t) and V2 (vec2 / f16vec2): two output channels a V2 (packed FP16).
_l1: from F[input][fi + tap offset] (the 20-wide tile) into a0.., before the ReLU.
_l1_store: their ReLU (zero off the image: in_) into L[channel][k] (the 18-wide tile).
_l2: from L[input][li2 + tap offset] into c0.., before the ReLU.
_l2_relu: their ReLU, as vec2 d0...
_l3: from d0.. into r0.. (5 corrections, 2 state channels, then the residual's 3 x RES x RES).
_out: the stores - CorrA, CorrB and (RES, pc.b.y = 1) the residual's RES x RES output pixels of each render pixel
into Res (pixel_shuffle's order: channel c x RES^2 + dy x RES + dx).
"""
import sys

import numpy as np
import torch


def h(x):
    return float(np.float16(x))


def lit(x):
    return f"{h(x):.8g}"


def conv(w, b, src, idx, width, out):
    """A 3x3 convolution: w out x in x 3 x 3, the input src[i][idx + offset] in a tile `width` wide."""
    co, ci = w.shape[0], w.shape[1]
    s = [f"V2 {out}{k} = V2({lit(b[2 * k])}, {lit(b[2 * k + 1])});" for k in range(co // 2)]
    for t in range(9):
        off = (t // 3) * width + t % 3
        for i in range(ci):
            s.append(f"{{ T v = {src}[{i}][{idx} + {off}];")
            for k in range(co // 2):
                s.append(f"{out}{k} += V2({lit(w[2 * k, i, t // 3, t % 3])}, {lit(w[2 * k + 1, i, t // 3, t % 3])}) * v;")
            s.append("}")
    return s


def dense(w, b):
    s = []
    for o in range(w.shape[0]):
        terms = " + ".join(f"{lit(w[o, 2 * k])} * d{k}.x + {lit(w[o, 2 * k + 1])} * d{k}.y" for k in range(w.shape[1] // 2))
        s.append(f"float r{o} = {lit(b[o])} + {terms};")
    return s


def l1_store(hid):
    s = ["bool in_ = all(greaterThanEqual(p, ivec2(0))) && all(lessThan(p, rs));", "V2 z = V2(0.0);"]
    for k in range(hid // 2):
        s.append(f"a{k} = in_ ? max(a{k}, z) : z; L[{2 * k}][k] = a{k}.x; L[{2 * k + 1}][k] = a{k}.y;")
    return s


def l2_relu(hid):
    return ["V2 z = V2(0.0);"] + [f"vec2 d{k} = vec2(max(c{k}, z));" for k in range(hid // 2)]


def out(res):
    s = ["imageStore(CorrA, p, 2.0 * tanh(0.5 * vec4(r0, r1, r2, r3)));",
         "imageStore(CorrB, p, vec4(2.0 * tanh(0.5 * r4), tanh(r5), tanh(r6), 0.0));"]
    if res:
        n = res * res
        s += [f"if (pc.b.y > 0.5) {{ ivec2 o = p * {res}, os = imageSize(Res);"]
        for dy in range(res):
            for dx in range(res):
                i = 7 + dy * res + dx
                s.append(f"if (o.x + {dx} < os.x && o.y + {dy} < os.y) "
                         f"imageStore(Res, o + ivec2({dx}, {dy}), vec4(r{i}, r{i + n}, r{i + 2 * n}, 0.0));")
        s.append("}")
    return s


def cstr(name, lines):
    out_ = f"static const char {name}[] =\n"
    out_ += "".join(f'    "{l}\\n"\n' for l in lines)
    return out_ + "    ;\n"


def main():
    src = sys.argv[1]
    dst = sys.argv[2] if len(sys.argv) > 2 else "../../runtime/nvn/vulkan/srnet_weights.h"
    p = sys.argv[3] if len(sys.argv) > 3 else "srnet"
    sd = {k: v.detach().cpu().numpy() for k, v in torch.load(src, map_location="cpu").items()}
    n = sum(v.size for v in sd.values())
    hid = sd["c1.weight"].shape[0]
    res = int(round(((sd["c3.weight"].shape[0] - 7) / 3) ** 0.5))
    with open(dst, "w", newline="\n") as f:
        f.write("// Generated by tools/srnet/export.py from %s (%d parameters, FP16 values): the tiny network of\n"
                % (src.replace("\\", "/").split("/")[-1], n))
        f.write("// DittoSR Net (exec.c srnet_run, shaders.c srnet.comp), its layers as straight-line GLSL. Trained on our\n")
        f.write("// own captures (tools/srnet).\n" if p == "srnet" else
                "// teacher's pairs (tools/srnet capture_exp.sh) - LOCAL research, never committed.\n")
        f.write(f"#define {p.upper()}_HID {hid}\n#define {p.upper()}_RES {res}\n")
        f.write(cstr(f"{p}_l1_glsl", conv(sd["c1.weight"], sd["c1.bias"], "F", "fi", 20, "a")))
        f.write(cstr(f"{p}_l1_store_glsl", l1_store(hid)))
        f.write(cstr(f"{p}_l2_glsl", conv(sd["c2.weight"], sd["c2.bias"], "L", "li2", 18, "c")))
        f.write(cstr(f"{p}_l2_relu_glsl", l2_relu(hid)))
        f.write(cstr(f"{p}_l3_glsl", dense(sd["c3.weight"][:, :, 0, 0], sd["c3.bias"])))
        f.write(cstr(f"{p}_out_glsl", out(res)))
    print(f"{dst}: {n} parameters, hidden {hid}, residual {res}")


if __name__ == "__main__":
    main()
